// a 1080x1350 picture of the slip for sharing
function card(n) {
  const [level, title, verse, love, work, luck, warn] = SLIPS[n - 1];
  const c = document.createElement('canvas'); c.width = 1080; c.height = 1350;
  const g = c.getContext('2d');
  g.fillStyle = '#120405'; g.fillRect(0, 0, 1080, 1350);
  g.fillStyle = '#ece5d3'; g.fillRect(90, 90, 900, 1170);
  g.strokeStyle = '#8c1b14'; g.lineWidth = 6; g.strokeRect(120, 120, 840, 1110);
  g.textAlign = 'center'; g.fillStyle = '#8c1b14';
  g.font = '600 40px "Kanit", sans-serif'; g.fillText(`เซียมซีผี · ใบที่ ${thaiNum(n)} · ${level}`, 540, 210);
  g.fillStyle = '#22180f'; g.font = '800 76px "Kanit", sans-serif'; g.fillText(title, 540, 320);
  const wrap = (text, x, y, max, lh) => {
    const seg = 'Segmenter' in Intl ? [...new Intl.Segmenter('th', { granularity: 'word' }).segment(text)].map((s) => s.segment) : text.split(' ');
    let line = '';
    for (const w of seg) { if (g.measureText(line + w).width > max && line) { g.fillText(line, x, y); y += lh; line = w.trimStart(); } else line += w; }
    g.fillText(line, x, y); return y + lh;
  };
  g.font = 'italic 400 38px "Kanit", sans-serif'; g.fillStyle = '#4a3a2c';
  let y = wrap(verse, 540, 400, 740, 54) + 20;
  g.textAlign = 'left';
  for (const [h, t] of [['ความรัก', love], ['การงาน', work], ['โชคลาภ', luck], ['ผีฝากเตือน', warn]]) {
    g.font = '600 34px "Kanit", sans-serif'; g.fillStyle = '#8c1b14'; g.fillText(h, 170, y); y += 48;
    g.font = '400 34px "Kanit", sans-serif'; g.fillStyle = '#22180f'; y = wrap(t, 170, y, 740, 46) + 18;
  }
  g.textAlign = 'center'; g.fillStyle = '#8c1b14'; g.font = '600 32px "Chakra Petch", sans-serif';
  g.fillText('phum132.github.io/ghost-diary', 540, 1190);
  return c;
}
